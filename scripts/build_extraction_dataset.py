class PromptRenderer:
    """Replays `OpenAIGenericClient.generate_response`'s message mutation.

    The cheap tier runs `cheap_llm_client_mode='generic_json_schema'`
    (config.py:236-237), so the JSON schema travels in `response_format` and is
    NOT injected into the prompt text. What IS appended, unconditionally, is the
    multilingual instruction on messages[0] (openai_generic_client.py:203);
    then every message goes through `_clean_input` (:149).

    A real client instance is constructed so `_clean_input` is graphiti's own
    code rather than a copy of it. No request is ever issued from it.
    """

    def __init__(self, group_id: str) -> None:
        self._group_id = group_id
        self._client = OpenAIGenericClient(
            config=LLMConfig(api_key="unused-offline", model="offline",
                             base_url="http://127.0.0.1:1"),
            structured_output_mode="json_schema",
        )

    def clean(self, text: str) -> str:
        """graphiti's own `_clean_input`, reached through a real client instance.

        Also used by the capture path: a captured prompt has already been through
        `_clean_input`, so matching its episode block back to the raw
        `Episodic.content` has to clean the graph side too or the comparison is
        between a cleaned string and an uncleaned one.
        """
        return self._client._clean_input(text)

    def render(self, messages: list[Message]) -> list[dict[str, str]]:
        msgs = [Message(role=m.role, content=m.content) for m in messages]
        msgs[0].content += get_extraction_language_instruction(self._group_id)
        return [{"role": m.role, "content": self.clean(m.content)} for m in msgs]


def response_schema(prompt_name: str) -> dict[str, Any]:
    """The `response_format` payload the cheap tier is served, maxItems included.

    Mirrors `OpenAIGenericClient._build_response_format` (json_schema branch,
    :118-124) and `graphiti_client._bound_index_arrays` (:116-126).
    """
    model = RESPONSE_MODELS[prompt_name]
    schema = model.model_json_schema()
    _bound_index_arrays(schema, MAX_INDEX_ARRAY)
    return {"type": "json_schema",
            "json_schema": {"name": model.__name__, "schema": schema}}


def _bound_index_arrays(node: object, max_items: int) -> None:
    if isinstance(node, dict):
        items = node.get("items")
        if (node.get("type") == "array" and isinstance(items, dict)
                and items.get("type") == "integer" and "maxItems" not in node):
            node["maxItems"] = max_items
        for value in node.values():
            _bound_index_arrays(value, max_items)
    elif isinstance(node, list):
        for value in node:
            _bound_index_arrays(value, max_items)


def target(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False)


def as_datetime(neo4j_ts: str) -> datetime:
    """Neo4j `toString(datetime)` -> a Python datetime shaped like graphiti's.

    graphiti holds `EpisodicNode.valid_at` as a datetime and interpolates it two
    different ways: `str(dt)` into `<REFERENCE_TIME>` (extract_edges.py:128) and
    `dt.isoformat()` into `previous_episodes` timestamps (edge_operations.py:193).
    Neo4j renders nanoseconds, Python only microseconds, so the trailing digits
    must be trimmed or the rendered prompt differs from production.
    """
    txt = neo4j_ts
    if txt.endswith("]"):          # Neo4j appends a named zone: "...+00:00[UTC]"
        txt = txt[:txt.rindex("[")]
    txt = txt.replace("Z", "+00:00")
    # Trim the FRACTIONAL field only. Anchoring the match matters: a naive
    # "keep the digits" filter also eats the digits out of the offset
    # ("...34.12-05:00" -> fraction 120500 and no offset at all), which silently
    # drops the timezone and yields a naive datetime. graphiti's EpisodicNode
    # .valid_at is tz-aware, and `str(dt)` on a naive datetime omits the
    # "+00:00" that production renders into <REFERENCE_TIME>.
    m = re.match(r"^(?P<head>.*?)\.(?P<frac>\d+)(?P<rest>.*)$", txt)
    if m:
        txt = f"{m['head']}.{m['frac'][:6].ljust(6, '0')}{m['rest']}"
    parsed = datetime.fromisoformat(txt)
    if parsed.tzinfo is None:      # bare timestamp: Neo4j stores these as UTC
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed


def _iso_z(neo4j_ts: str | None) -> str | None:
    """The `valid_at`/`invalid_at` shape the Edge schema asks the model for:
    'ISO 8601 with Z suffix' (extract_edges.py:42-47)."""
    if not neo4j_ts:
        return None
    return as_datetime(neo4j_ts).isoformat().replace("+00:00", "Z")


class SimIndex:
    """Cosine similarity over the embeddings the graph already stores.

    The same embedder wrote these vectors during ingestion, so ranking with them
    reproduces the vector half of graphiti's candidate search at zero cost and
    with no embedder call. (graphiti fuses vector with a fulltext leg via RRF, so
    the candidate SET overlaps but the ORDER can differ -- recorded per record in
    `meta.fidelity`.)
    """

    def __init__(self, vectors: dict[str, list[float]]) -> None:
        self.rows = {u: i for i, u in enumerate(vectors)}
        if not vectors:
            self.matrix = np.zeros((0, 1), dtype=np.float32)
            return
        m = np.asarray(list(vectors.values()), dtype=np.float32)
        norms = np.linalg.norm(m, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        self.matrix = m / norms

    def against(self, uuid: str, others: list[str]) -> np.ndarray:
        """Cosine of `uuid` against each of `others`, in order."""
        if uuid not in self.rows or not others:
            return np.zeros(len(others), dtype=np.float32)
        idx = [self.rows[o] for o in others if o in self.rows]
        if len(idx) != len(others):
            return np.array([float(self.matrix[self.rows[uuid]] @ self.matrix[self.rows[o]])
                             if o in self.rows else 0.0 for o in others], dtype=np.float32)
        return self.matrix[idx] @ self.matrix[self.rows[uuid]]


