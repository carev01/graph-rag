#!/usr/bin/env python
"""Build a qwen-3.5-4b fine-tuning dataset for graphiti 0.30.1's cheap extraction tier.

READ-ONLY. Opens one Neo4j session in READ access mode and never writes. Makes no
LLM call, no embedder call and no DocExtractor call, so it costs nothing to run.

WHY THIS SHAPE
--------------
`src/graph_extract/usage.py` records token COUNTS only (`record("llm",
prompt=<int>, completion=<int>, cached=<int>)`, usage.py:42-47). No prompt or
completion text is persisted anywhere in this repo, so distillation data is a
LABELLING job, not a capture job. What we do have is the live `backup-docs`
graph, which stores enough to rebuild (prompt, target) pairs offline:

  * `:Episodic.content` is the exact `episode_content` string that went into the
    prompt. `IngestDriver` adds one episode per `add_episode` call
    (ingest_driver.py:191-194) and graphiti's `concatenate_episodes` returns a
    single episode's content verbatim (utils/text_utils.py:69-70).
  * `(:Episodic)-[:MENTIONS]->(:Entity)` gives per-episode entity attribution.
  * `RELATES_TO.episodes` gives per-episode fact attribution.
  * `Entity.name_embedding` and `RELATES_TO.fact_embedding` are populated on
    every node/edge (768-d), so graphiti's dedup CANDIDATE lists can be
    reconstructed without calling the embedder.

The prompts themselves are not paraphrased here: this module imports graphiti's
real `prompt_library` functions and replays the message mutation that
`OpenAIGenericClient.generate_response` performs before the request goes out
(the multilingual suffix on messages[0], then `_clean_input` on every message --
openai_generic_client.py:203 and :149).

WHAT IS FAITHFUL AND WHAT IS NOT
--------------------------------
Every record carries `meta.provenance` and `meta.fidelity` so this is auditable
per example rather than only in prose. Summary:

  graph_derived         the target is what the pipeline actually produced, with
                        the known post-dedup caveats recorded in `fidelity`.
  graph_derived_negative  a real negative: the call happened and the model
                        correctly answered "no duplicate".
  synthetic_alias_positive  the NEW FACT was generated by swapping a term for a
                        non-canonical alias listed in `ontology.py`'s
                        EXTRACTION_INSTRUCTIONS. The duplicate label follows from
                        the project's own canonicalisation rule, but no model
                        ever emitted this string. REVIEW BEFORE TRAINING.

The graph cannot supply true positives for either index-picking prompt: when
graphiti merges a duplicate it keeps the EXISTING text and discards the newly
extracted paraphrase (edge_operations.py resolve path), so the string the model
actually produced is gone. `--report` prints exactly what is missing.

CAPTURED PAIRS (--from-capture)
------------------------------
Since this module was written, `usage.capture_llm_call` landed and an authorised
capture run recorded what `upstage/solar-pro4` ACTUALLY emitted on the same 83
pilot articles. `--from-capture PATH` builds from those real pairs instead of
reconstructing targets from the graph. It fixes the two holes the graph-derived
build cannot fill -- `dedupe_nodes` had no positives at all, and `resolve_edge`
positives were synthetic -- at the price of two new problems, both solved here
rather than papered over:

  * the capture carries no article_id, so attribution is recovered offline
    (`CaptureAttributor`) and anything not attributable to exactly ONE article is
    dropped rather than assigned, because the split is by article;
  * the capture carries the model's MISTAKES, so every completion is validated
    (`validate_capture`) against its schema and against the semantic constraints
    a schema cannot express.

REPAIR POLICY (`repair_capture`, `--no-repair` to disable)
---------------------------------------------------------
This fine-tune REPLACES solar-pro4; it does not clone it. So where the correct
answer is DERIVABLE, the target is corrected rather than discarded -- a derived
correction is a verified correct answer, and a better one than the model's.
Where the correct answer would have to be GENERATED, nothing is invented and the
record is dropped. That line is the whole of the policy:

  repaired (derivable)                       dropped (needs generation)
  --------------------------------------     ----------------------------------
  `episode_indices` outside the prompt's     a summary over MAX_SUMMARY_CHARS:
  range -> `[0]`. Exactly one episode is     the correct answer is a SHORTER
  ever in scope (see below), and the         summary, which only a model can
  schema's own default is `[0]`.             write. `truncate_at_sentence` is
                                             what graphiti applies downstream,
  an endpoint name absent from ENTITIES,     but truncation as a TARGET teaches
  or a self-edge -> omit that edge.          "write long, then stop abruptly",
  `edge_operations.py:218-239` rejects       which is a different defect, not a
  both outright, so the corpus lost them     fix.
  either way.

Repair is PER ITEM inside a completion, never per record: one bad edge costs
that edge, not the rest of the record's work. Every repaired record carries
`meta.repaired` -- one entry per change, naming the defect class and the specific
item -- because a corrected target that does not say so is indistinguishable
from an observed one, and per-example auditability is this dataset's whole value.
`meta.provenance` stays `captured` (the PROMPT is still exactly what went on the
wire) and `meta.fidelity` says the target was corrected.

THE SINGLE-EPISODE CLAIM, verified four ways
--------------------------------------------
`episode_indices` is repairable to `[0]` only because exactly one episode is ever
in scope. That is not assumed here:

  1. `ingest_driver.py:188-196` calls `add_text_episode` once per chunk.
  2. `graphiti.add_episode` (graphiti.py:1099-1111) constructs ONE `EpisodicNode`
     and passes it singular to `extract_nodes` / `_extract_and_resolve_edges`,
     which both do `episodes = episode if isinstance(episode, list) else
     [episode]` -- so `len(episodes) == 1`.
  3. graphiti emits its "**Episode Attribution**" instruction only when
     `len(episodes) > 1` (`edge_operations.py:170-181`,
     `node_operations.py:104-112`). It appears in ZERO of the 4,743 captured
     prompts.
  4. The `Edge.episode_indices` / `ExtractedEntity.episode_indices` fields
     default to `[0]` and their own descriptions say "When processing a single
     episode, this should be [0]".

The provenance consequence was checked on the live graph and recorded in
`docs/proposals/2026-09-15-bulk-ingest-assessment.md` (addendum 2026-09-17):
0 unattributed facts, 0 dangling references.

The graph-derived path is unchanged and still the only source for prompts the
capture missed, and a useful cross-check against it.

Usage
-----
    uv run --extra dev python scripts/build_extraction_dataset.py --out data/ft
    uv run --extra dev python scripts/build_extraction_dataset.py --limit 20 \
        --out docs/proposals/samples --sample-only
    uv run --extra dev python scripts/build_extraction_dataset.py \
        --from-capture /path/to/llm-capture.jsonl --out data/ft-captured --upsample
"""
