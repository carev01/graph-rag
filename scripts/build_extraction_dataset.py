@dataclass
class Builder:
    graph: Graph
    renderer: PromptRenderer
    instructions: str
    rng: random.Random
    entity_types_context: list[dict] = field(init=False)
    type_id_by_label: dict[str, int] = field(init=False)
    birth_episode: dict[str, str] = field(init=False)
    ent_sim: SimIndex = field(init=False)
    fact_sim: SimIndex = field(init=False)

    def __post_init__(self) -> None:
        self.ent_sim = SimIndex({u: e.embedding for u, e in self.graph.entities.items()})
        self.fact_sim = SimIndex({u: f.embedding for u, f in self.graph.facts.items()})
        self.entity_types_context = _build_entity_types_context(ENTITY_TYPES)
        self.type_id_by_label = {
            c["entity_type_name"]: c["entity_type_id"] for c in self.entity_types_context}
        # An entity's birth episode: the earliest-processed episode that MENTIONS
        # it. MENTIONS is written by the same add_episode that created the node,
        # so the earliest one is where extraction first emitted it.
        first: dict[str, str] = {}
        for ep in self.graph.episodes_in_order():
            for ent_uuid in self.graph.mentions.get(ep.uuid, []):
                first.setdefault(ent_uuid, ep.uuid)
        self.birth_episode = first

    # ---- shared context pieces ------------------------------------------- #
    def previous_episodes(self, ep: Episode) -> list[dict[str, Any]]:
        """Replay `retrieve_episodes(reference_time, last_n=RELEVANT_SCHEMA_LIMIT)`.

        graphiti orders by valid_at desc and caps at 10 (graphiti.py:1088-1093).
        Only episodes that already existed when `ep` was processed are eligible,
        which `created_at` gives us.
        """
        prior = [e for e in self.graph.episodes.values()
                 if e.created_at < ep.created_at and e.valid_at <= ep.valid_at]
        prior.sort(key=lambda e: (e.valid_at, e.created_at), reverse=True)
        chosen = list(reversed(prior[:RELEVANT_SCHEMA_LIMIT]))
        return [{"content": e.content, "timestamp": as_datetime(e.valid_at).isoformat()}
                for e in chosen]

    def entities_of(self, ep: Episode) -> list[Entity]:
        ents = [self.graph.entities[u] for u in self.graph.mentions.get(ep.uuid, [])
                if u in self.graph.entities]
        return sorted(ents, key=lambda e: e.created_at)

    def type_id(self, ent: Entity) -> int:
        for label in ent.labels:
            if label != "Entity" and label in self.type_id_by_label:
                return self.type_id_by_label[label]
        return 0

    # ---- extract_nodes.extract_text -------------------------------------- #
    def extract_text(self, ep: Episode) -> dict[str, Any] | None:
        ents = self.entities_of(ep)
        if not ents:
            return None
        context = {
            "episode_content": ep.content,
            "episode_timestamp": as_datetime(ep.valid_at).isoformat(),
            "previous_episodes": self.previous_episodes(ep),
            "custom_extraction_instructions": self.instructions,
            "entity_types": self.entity_types_context,
            "source_description": ep.source_description,
        }
        answer = {"extracted_entities": [
            {"name": e.name, "entity_type_id": self.type_id(e), "episode_indices": [0]}
            for e in ents]}
        return self._record(
            "extract_nodes.extract_text",
            prompt_library.extract_nodes.extract_text(context), answer, ep,
            provenance="graph_derived",
            fidelity=["names are POST-dedup canonical names; where dedup merged an "
                      "extracted name into an existing node, the string the model "
                      "emitted is not recoverable",
                      "entities dropped by the noise filter or by graphiti's empty-name "
                      "filter are absent from the target"])

    # ---- extract_edges.edge ---------------------------------------------- #
    def edge(self, ep: Episode) -> dict[str, Any] | None:
        ents = self.entities_of(ep)
        if not ents:
            return None
        by_uuid = {e.uuid: e for e in ents}
        facts = [f for f in self.graph.facts.values() if ep.uuid in f.episodes]
        # The prompt REQUIRES endpoint names to come from the ENTITIES list
        # (extract_edges.py:146); drop any fact whose endpoints are not both there.
        facts = [f for f in facts
                 if f.source_uuid in by_uuid and f.target_uuid in by_uuid]
        if not facts:
            return None
        facts.sort(key=lambda f: f.created_at)
        context = {
            "previous_episodes": self.previous_episodes(ep),
            "episode_content": ep.content,
            "nodes": [{"name": e.name, "entity_types": e.labels} for e in ents],
            "reference_time": as_datetime(ep.valid_at),
            "edge_types": self._edge_types_context(),
            "custom_extraction_instructions": self.instructions,
        }
        answer = {"edges": [
            {"source_entity_name": by_uuid[f.source_uuid].name,
             "target_entity_name": by_uuid[f.target_uuid].name,
             "relation_type": f.name,
             "fact": f.fact,
             "valid_at": _iso_z(f.valid_at),
             "invalid_at": _iso_z(f.invalid_at),
             "episode_indices": [0]}
            for f in facts]}
        return self._record(
            "extract_edges.edge", prompt_library.extract_edges.edge(context), answer, ep,
            provenance="graph_derived",
            fidelity=["facts the model emitted that were then merged into an existing "
                      "edge appear here with the SURVIVING edge's text, not the text "
                      "the model produced",
                      "valid_at is set deterministically from the episode reference "
                      "time by deterministic_valid_at when that patch is enabled, so "
                      "it is not always a model-produced value"])

    def _edge_types_context(self) -> list[dict[str, Any]]:
        """Mirrors edge_operations.py:145-165 exactly, signatures included."""
        signatures: dict[str, list[tuple[str, str]]] = defaultdict(list)
        for signature, names in EDGE_TYPE_MAP.items():
            for name in names:
                signatures[name].append(signature)
        return [{"fact_type_name": name,
                 "fact_type_signatures": signatures.get(name, [("Entity", "Entity")]),
                 "fact_type_description": model.__doc__}
                for name, model in EDGE_TYPES.items()]

    # ---- extract_nodes.extract_summaries_batch ---------------------------- #
    def summaries_batch(self, ep: Episode) -> list[dict[str, Any]]:
        """Only entities that would actually have reached the LLM.

        The summary LLM is NOT called for most nodes. `_extract_entity_summaries_batch`
        appends the node's edge facts to its summary and, when the result is
        `<= MAX_SUMMARY_CHARS * 2` (2,000 chars), assigns it directly and
        `continue`s with no LLM call (node_operations.py:880-882). Only the
        overflow cases are batched into `extract_summaries_batch`. Our call sites
        never pass `skip_fact_appending=True`, so that shortcut is the live path.

        Emitting one record per summarised entity would therefore have produced
        mostly examples of calls that never happened. This applies the real gate.
        It is an approximation in one direction: `Entity.summary` is the FINAL
        summary, whereas the gate saw the prior one, so this over-admits rather
        than under-admits.
        """
        ents = [e for e in self.entities_of(ep) if self._needs_llm_summary(e, ep)]
        out: list[dict[str, Any]] = []
        descriptions = {name: _truncate_type_description(model.__doc__ or "")
                        for name, model in ENTITY_TYPES.items() if model.__doc__}
        for i in range(0, len(ents), MAX_NODES):
            batch = ents[i:i + MAX_NODES]
            context = {
                "entities": [{"name": e.name, "summary": "", "entity_types": e.labels,
                              "attributes": {}} for e in batch],
                "episode_content": ep.content,
                "previous_episodes": self.previous_episodes(ep),
                "entity_type_descriptions": descriptions,
            }
            answer = {"summaries": [{"name": e.name, "summary": e.summary} for e in batch]}
            rec = self._record(
                "extract_nodes.extract_summaries_batch",
                prompt_library.extract_nodes.extract_summaries_batch(context), answer, ep,
                provenance="graph_derived",
                fidelity=["WEAKEST target in this set: Entity.summary is the FINAL "
                          "summary after every later episode updated it, not the "
                          "summary produced at this episode. Existing-summary state at "
                          "call time is also unrecoverable, so the prompt shows an "
                          "empty prior summary.",
                          "the >2*MAX_SUMMARY_CHARS gate that decides whether the LLM "
                          "is called at all (node_operations.py:880-882) is replayed "
                          "here against the FINAL summary, so a few of these calls may "
                          "not have happened in production"])
            rec["meta"]["batch_index"] = i // MAX_NODES
            out.append(rec)
        return out

    def _needs_llm_summary(self, ent: Entity, ep: Episode) -> bool:
        """Replay node_operations.py:871-889's gate for one node in one episode."""
        if not ent.summary:
            return False
        facts = [f.fact for f in self.graph.facts.values()
                 if ep.uuid in f.episodes
                 and ent.uuid in (f.source_uuid, f.target_uuid) and f.fact]
        combined = ent.summary
        if facts:
            combined = f"{combined}\n{chr(10).join(facts)}".strip()
        return len(combined) > MAX_SUMMARY_CHARS * 2

    # ---- dedupe_edges.resolve_edge ---------------------------------------- #
    def resolve_edge_negatives(self) -> list[dict[str, Any]]:
        """Facts that arrived at a node pair that already had facts, and were kept.

        graphiti short-circuits with NO LLM call when both candidate lists are
        empty (edge_operations.py:653), so only facts with a non-empty
        `related_edges` produced a call. `contradiction_gate` empties
        `existing_edges` for every ingest, so FACT INVALIDATION CANDIDATES is []
        in production and the prompt carries ONE index range.
        """
        by_pair: dict[tuple[str, str], list[Fact]] = defaultdict(list)
        for f in self.graph.facts.values():
            # DIRECTIONAL, deliberately: graphiti's duplicate candidates come
            # from EntityEdge.get_between_nodes, whose Cypher is
            # `(n {uuid:$source})-[e:RELATES_TO]->(m {uuid:$target})`
            # (edges.py:421-423). Grouping by an UNDIRECTED pair would show the
            # model B->A facts production never put in EXISTING FACTS, and would
            # mislabel as a "negative" a fact whose real candidate list was empty
            # (in which case edge_operations.py:653 issues no LLM call at all).
            key = (f.source_uuid, f.target_uuid)
            by_pair[key].append(f)
        out: list[dict[str, Any]] = []
        for facts in by_pair.values():
            facts.sort(key=lambda f: f.created_at)
            for i, f in enumerate(facts):
                candidates = facts[:i]
                if not candidates:
                    continue
                ranked = self._rank_facts(f, candidates)[:DEFAULT_SEARCH_LIMIT]
                out.append(self._resolve_edge_record(
                    f, ranked, {"duplicate_facts": [], "contradicted_facts": []},
                    provenance="graph_derived_negative",
                    fidelity=["true negative: this fact survived as its own edge, so "
                              "the model answered 'no duplicate' and was not overruled",
                              "candidate ORDER is by stored fact_embedding cosine; "
                              "graphiti ranks by hybrid fulltext+vector RRF, so the "
                              "set overlaps but the indices may differ"]))
        return out

    def resolve_edge_alias_positives(self) -> list[dict[str, Any]]:
        """Synthetic positives. See CANONICAL_ALIASES and the module docstring."""
        out: list[dict[str, Any]] = []
        by_pair: dict[tuple[str, str], list[Fact]] = defaultdict(list)
        for f in self.graph.facts.values():
            # DIRECTIONAL, deliberately: graphiti's duplicate candidates come
            # from EntityEdge.get_between_nodes, whose Cypher is
            # `(n {uuid:$source})-[e:RELATES_TO]->(m {uuid:$target})`
            # (edges.py:421-423). Grouping by an UNDIRECTED pair would show the
            # model B->A facts production never put in EXISTING FACTS, and would
            # mislabel as a "negative" a fact whose real candidate list was empty
            # (in which case edge_operations.py:653 issues no LLM call at all).
            key = (f.source_uuid, f.target_uuid)
            by_pair[key].append(f)
        for facts in by_pair.values():
            facts.sort(key=lambda f: f.created_at)
            for f in facts:
                swapped = self._alias_swap(f.fact)
                if swapped is None:
                    continue
                new_fact, rule = swapped
                others = [o for o in facts if o.uuid != f.uuid]
                pool = [f] + self._rank_facts(f, others)[:DEFAULT_SEARCH_LIMIT - 1]
                self.rng.shuffle(pool)
                idx = pool.index(f)
                out.append(self._resolve_edge_record(
                    f, pool, {"duplicate_facts": [idx], "contradicted_facts": []},
                    new_fact_text=new_fact,
                    provenance="synthetic_alias_positive",
                    fidelity=[f"NEW FACT was generated by the rule '{rule}' from "
                              "ontology.py's canonical-name list. No model emitted it. "
                              "Review before training.",
                              "positives cannot be graph-derived: graphiti discards the "
                              "merged-away text and keeps the existing edge's fact"]))
        return out

    def _rank_facts(self, target_fact: Fact, candidates: list[Fact]) -> list[Fact]:
        if not candidates:
            return []
        sims = self.fact_sim.against(target_fact.uuid, [c.uuid for c in candidates])
        order = np.argsort(-sims, kind="stable")
        return [candidates[i] for i in order]

    def _alias_swap(self, fact: str) -> tuple[str, str] | None:
        for canonical, aliases in CANONICAL_ALIASES.items():
            if canonical in fact:
                alias = aliases[0]
                return fact.replace(canonical, alias, 1), f"{canonical} -> {alias}"
        return None

    def _resolve_edge_record(self, f: Fact, candidates: list[Fact], answer: dict,
                             *, provenance: str, fidelity: list[str],
                             new_fact_text: str | None = None) -> dict[str, Any]:
        context = {
            "existing_edges": [{"idx": i, "fact": c.fact} for i, c in enumerate(candidates)],
            "new_edge": new_fact_text if new_fact_text is not None else f.fact,
            # Always [] in production: contradiction_gate returns SearchResults()
            # for the unfiltered invalidation search (contradiction_gate.py:98-101).
            "edge_invalidation_candidates": [],
        }
        ep_uuid = f.episodes[0] if f.episodes else ""
        ep = self.graph.episodes.get(ep_uuid)
        rec = self._record("dedupe_edges.resolve_edge",
                           prompt_library.dedupe_edges.resolve_edge(context), answer, ep,
                           provenance=provenance, fidelity=fidelity)
        rec["meta"]["fact_uuid"] = f.uuid
        rec["meta"]["n_candidates"] = len(candidates)
        return rec

    # ---- dedupe_nodes.nodes ----------------------------------------------- #
    def dedupe_nodes(self, ep: Episode) -> dict[str, Any] | None:
        """Only entities graphiti's deterministic pass could NOT resolve reach the LLM.

        `resolve_extracted_nodes` runs `_resolve_with_similarity` (exact
        normalized-name, then MinHash/LSH at Jaccard >= 0.9) per extracted node
        and only appends the survivors to `unresolved_indices`
        (node_operations.py:649-670). Nodes with NO candidates never reach the LLM
        at all. We replay that with graphiti's own helpers so the distribution
        matches production instead of being systematically easier.
        """
        born = [e for e in self.entities_of(ep) if self.birth_episode.get(e.uuid) == ep.uuid]
        if not born:
            return None
        pool = [e for e in self.graph.entities.values() if e.created_at < ep.created_at]
        if not pool:
            return None
        pool_uuids = [e.uuid for e in pool]

        unresolved: list[Entity] = []
        candidates_union: dict[str, Entity] = {}
        for ent in born:
            sims = self.ent_sim.against(ent.uuid, pool_uuids)
            order = np.argsort(-sims, kind="stable")[:NODE_DEDUP_CANDIDATE_LIMIT]
            cands = [pool[i] for i in order if sims[i] >= NODE_DEDUP_COSINE_MIN_SCORE]
            if not cands:
                continue
            indexes = _build_candidate_indexes([_as_node(c) for c in cands])
            state = DedupResolutionState(resolved_nodes=[None], uuid_map={},
                                         unresolved_indices=[])
            _resolve_with_similarity([_as_node(ent)], indexes, state)
            if state.resolved_nodes[0] is not None:
                continue      # deterministic pass caught it: no LLM call happened
            unresolved.append(ent)
            for c in cands:
                candidates_union.setdefault(c.uuid, c)
        if not unresolved:
            return None

        # Insertion order, NOT created_at: graphiti concatenates each extracted
        # node's similarity-ranked candidates in extraction order and de-dupes
        # keeping the first occurrence (`_merge_candidate_nodes`,
        # node_operations.py:387-404). `candidates_union` is populated in exactly
        # that order above; re-sorting would renumber every `candidate_id`.
        cand_list = list(candidates_union.values())
        context = {
            "extracted_nodes": [
                {"id": i, "name": e.name, "entity_type": e.labels,
                 "entity_type_description": _get_entity_type_description(
                     e.labels, ENTITY_TYPES)}
                for i, e in enumerate(unresolved)],
            "existing_nodes": [
                {"candidate_id": i, "name": c.name, "entity_types": c.labels,
                 "summary": c.summary[:120] if c.summary else ""}
                for i, c in enumerate(cand_list)],
            "episode_content": ep.content,
            "previous_episodes": self.previous_episodes(ep),
        }
        answer = {"entity_resolutions": [
            {"id": i, "name": e.name, "duplicate_candidate_id": -1}
            for i, e in enumerate(unresolved)]}
        return self._record(
            "dedupe_nodes.nodes", prompt_library.dedupe_nodes.nodes(context), answer, ep,
            provenance="graph_derived_negative",
            fidelity=["negatives only. These entities became their own nodes, so -1 is "
                      "the label the pipeline acted on.",
                      "POSITIVES ARE ABSENT: when the LLM resolves a duplicate, the "
                      "extracted name is discarded and only the surviving node remains, "
                      "so no positive can be graph-derived. A model trained on this "
                      "split alone will learn to always answer -1.",
                      "candidate ORDER is by stored name_embedding cosine; graphiti "
                      "ranks by hybrid fulltext+vector RRF"])

    # ---- record assembly --------------------------------------------------- #
    def _record(self, prompt_name: str, messages: list[Message], answer: dict,
                ep: Episode | None, *, provenance: str,
                fidelity: list[str]) -> dict[str, Any]:
        rendered = self.renderer.render(messages)
        rendered.append({"role": "assistant", "content": target(answer)})
        return {
            "prompt_name": prompt_name,
            "response_schema": RESPONSE_MODELS[prompt_name].__name__,
            "messages": rendered,
            "meta": {
                "provenance": provenance,
                "fidelity": fidelity,
                "episode_uuid": ep.uuid if ep else None,
                "article_id": ep.article_id if ep else None,
                "chunk_index": ep.chunk_index if ep else None,
            },
        }


def _as_node(e: Entity) -> EntityNode:
    """A minimal EntityNode so graphiti's own dedup helpers can be reused verbatim."""
    return EntityNode(uuid=e.uuid, name=e.name, group_id="backup-docs",
                      labels=list(e.labels), summary=e.summary)


