# split, weighting, output
# --------------------------------------------------------------------------- #
# The fine-tune replaces solar-pro4 COMPLETELY, so the mix tracks the measured
# LLM-time share rather than hedging toward the calls a 4B is most likely to get
# right. `extract_edges.edge` is the largest real share AND the hardest at 4B, so
# under-weighting it optimises hardest for the part we were always going to get.
# resolve_edge keeps a modest boost above its 22.9% time share because every
# recorded out-of-range failure in this project landed on the index arrays.
TARGET_MIX = {
    "extract_edges.edge": 0.34,
    "dedupe_edges.resolve_edge": 0.25,
    "extract_nodes.extract_summaries_batch": 0.18,
    "extract_nodes.extract_text": 0.13,
    "dedupe_nodes.nodes": 0.10,
}


def assign_loss_weights(records: list[dict], basis: str = "full") -> dict[str, float]:
    """Set `meta.loss_weight` so TARGET_MIX is the token share under `basis`.

    Two masking regimes disagree about what "a prompt's share of the gradient"
    means, and using the wrong one silently defeats the whole point of weighting:

    - `basis="completion"`: standard completion-masked SFT backprops only through
      the last message, so a prompt's influence on the gradient is its share of
      COMPLETION tokens alone. Measured on the full build, that share diverges
      wildly from example count -- index-picking is ~49% of examples but only a
      few percent of completion tokens, because a resolve_edge target is ~12
      tokens while a summaries_batch target is ~1,494. Weights under this basis
      run to a ~100x spread (docs/proposals/2026-09-16-extraction-finetune-
      dataset.md §6).
    - `basis="full"` (default): training on FULL SEQUENCES, with no
      completion-only loss mask, means every message's tokens carry gradient, so
      a prompt's share of the gradient is its share of ALL tokens in the record
      -- dominated by the long `episode_content`/`previous_episodes` prompt
      context, not by the short target. This is the correct basis whenever the
      trainer does not mask loss to completions.

    The emitted `meta.loss_weight` assumes whichever `basis` was requested, and
    each record also carries `meta.loss_basis` so the file is self-describing --
    weights computed for one masking regime and silently trained under the other
    are indistinguishable from correct ones by inspection alone.

    A trainer that ignores per-example weights (e.g. TRL's `SFTTrainer`, which
    Unsloth wraps) should upsample by repetition instead (`--upsample`); the
    printed table gives the multipliers either way.
    """
    if basis not in ("full", "completion"):
        raise ValueError(f"basis must be 'full' or 'completion', got {basis!r}")
    tokens: dict[str, int] = defaultdict(int)
    for r in records:
        if basis == "full":
            tokens[r["prompt_name"]] += sum(
                max(1, len(m["content"]) // 4) for m in r["messages"])
        else:
            tokens[r["prompt_name"]] += max(1, len(r["messages"][-1]["content"]) // 4)
    total = sum(tokens.values())
    weights = {}
    for name, share in TARGET_MIX.items():
        have = tokens.get(name, 0)
        weights[name] = (share * total / have) if have else 0.0
    # Normalise so the mean weight is 1.0 -- keeps the effective learning rate
    # comparable to an unweighted run.
    mean = sum(weights[r["prompt_name"]] for r in records) / max(1, len(records))
    for name in weights:
        weights[name] /= mean or 1.0
    for r in records:
        r["meta"]["loss_weight"] = round(weights[r["prompt_name"]], 4)
        r["meta"]["loss_basis"] = basis
    return weights


def split_of(article_id: str, val_fraction: float) -> str:
    """Split by ARTICLE, never by episode: episodes of one article share entities
    and near-identical text, so an episode-level split leaks the answer."""
    if not article_id:
        return "train"
    h = int(hashlib.sha256(article_id.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    return "val" if h < val_fraction else "train"


def _tokens_by_prompt(records: list[dict], basis: str) -> dict[str, int]:
    """Approximate token count per prompt name, chars/4, under `basis`."""
    tokens: dict[str, int] = defaultdict(int)
    for r in records:
        msgs = r["messages"] if basis == "full" else r["messages"][-1:]
        tokens[r["prompt_name"]] += sum(max(1, len(m["content"]) // 4) for m in msgs)
    return tokens


def upsample_train(train: list[dict], max_repeat: int, basis: str = "full") -> list[dict]:
    """Repeat TRAIN records so TARGET_MIX is approached in TOKEN share.

    **Not** `round(loss_weight)`. That weight is mean-normalised so the effective
    learning rate stays comparable to an unweighted run -- correct for
    per-example weighting, wrong for repetition. Normalisation makes the numbers
    RELATIVE, and a repeat count has to be ABSOLUTE. Using it directly landed
    `resolve_edge` at 11.7% of tokens against a 25% target, under half, while
    printing a report that looked reasonable.

    The right factor is the raw ratio `target_share / actual_share`. Repetition
    can only ADD tokens, so the prompt with the largest `tokens/target` ratio is
    binding: it gets one copy and every other prompt is scaled relative to it.

    **A prompt already OVER its target cannot be brought down this way** -- only
    by discarding examples, which this deliberately does not do (the
    over-represented prompt here is `extract_edges.edge`, the hardest task and
    the one we least want to throw data away from). `_print_upsample_report`
    shows the residual gap rather than hiding it.

    TRAIN ONLY: never apply to `val` -- repeating validation examples weights the
    val loss toward the repeated prompts, and a repeat crossing the split
    boundary would be leakage.

    Every emitted copy, including the first, gets a distinct `meta.repeat_index`
    so a deduplicating pipeline downstream cannot silently collapse them back.
    """
    tokens = _tokens_by_prompt(train, basis)
    ratios = {p: tokens[p] / TARGET_MIX[p]
              for p in tokens if TARGET_MIX.get(p) and tokens[p]}
    if not ratios:
        return list(train)
    binding = max(ratios.values())
    repeats = {
        p: min(max(1, round(binding * TARGET_MIX[p] / tokens[p])), max_repeat)
        for p in ratios
    }
    capped = [p for p in repeats
              if round(binding * TARGET_MIX[p] / tokens[p]) > max_repeat]
    if capped:
        logger.warning(
            "  upsample: %s hit the --max-repeat %d cap and will stay BELOW "
            "target; raise the cap or accept the gap", ", ".join(sorted(capped)),
            max_repeat)
    out: list[dict] = []
    for r in train:
        for i in range(repeats.get(r["prompt_name"], 1)):
            rec = dict(r)
            rec["meta"] = dict(r["meta"])
            rec["meta"]["repeat_index"] = i
            out.append(rec)
    return out


def apply_mix(records: list[dict], rng: random.Random,
              limit: int | None) -> list[dict]:
    by_name: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        by_name[r["prompt_name"]].append(r)
    if limit is None:
        # No cap requested: the binding prompt is whichever is scarcest relative
        # to its target share. Scale every bucket to that.
        limit = min(int(len(v) / TARGET_MIX[k])
                    for k, v in by_name.items() if v and TARGET_MIX.get(k))
    out: list[dict] = []
    for name, share in TARGET_MIX.items():
        want = max(1, round(limit * share))
        have = by_name.get(name, [])
        rng.shuffle(have)
        out.extend(have[:want])
    rng.shuffle(out)
    return out


async def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", required=True, type=Path,
                   help="output directory for train.jsonl / val.jsonl / schemas.json")
    p.add_argument("--limit", type=int, default=None,
                   help="total examples to emit across both splits (before mixing)")
    p.add_argument("--prompts", default=",".join(TARGET_MIX),
                   help="comma-separated prompt names to build")
    p.add_argument("--val-fraction", type=float, default=0.2)
    p.add_argument("--seed", type=int, default=20260916)
    p.add_argument("--tier", choices=("cheap", "strong"), default="cheap",
                   help="which tier's extraction instructions to render")
    p.add_argument("--no-synthetic-positives", action="store_true",
                   help="omit the synthetic_alias_positive resolve_edge records")
    p.add_argument("--loss-basis", choices=("full", "completion"), default="full",
                   help="compute meta.loss_weight over full-record tokens (matches "
                        "training on full sequences, no completion-only loss mask) or "
                        "completion-only tokens (matches completion-masked SFT); "
                        "default full")
    p.add_argument("--upsample", action="store_true",
                   help="emit each TRAIN record round(loss_weight) times (min 1, capped "
                        "at --max-repeat) instead of relying on meta.loss_weight at train "
                        "time; val is never upsampled")
    p.add_argument("--max-repeat", type=int, default=12,
                   help="cap on repeats per record when --upsample is set (default 8)")
    p.add_argument("--sample-only", action="store_true",
                   help="write a single sample.jsonl of --limit records, no split")
    p.add_argument("--report", action="store_true", default=True,
                   help="print the derivability report (default on)")
    args = p.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    s = get_extract_settings()
    rng = random.Random(args.seed)

    logger.info("loading %s (read-only) ...", s.neo4j_uri.split("@")[-1])
    graph = await load_graph(s.neo4j_uri, s.neo4j_user, s.neo4j_password, s.group_id)
    logger.info("loaded: %d episodes, %d entities, %d facts",
                len(graph.episodes), len(graph.entities), len(graph.facts))
    if not graph.episodes:
        logger.error("no episodes in group %r -- nothing to build", s.group_id)
        return 1

    instructions = EXTRACTION_INSTRUCTIONS + (
        CHEAP_TIER_SALIENCE if args.tier == "cheap" else "")
    builder = Builder(graph=graph, renderer=PromptRenderer(s.group_id),
                      instructions=instructions, rng=rng)

    wanted = set(args.prompts.split(","))
    records: list[dict] = []
    for ep in graph.episodes_in_order():
        if "extract_nodes.extract_text" in wanted:
            r = builder.extract_text(ep)
            if r:
                records.append(r)
        if "extract_edges.edge" in wanted:
            r = builder.edge(ep)
            if r:
                records.append(r)
        if "extract_nodes.extract_summaries_batch" in wanted:
            records.extend(builder.summaries_batch(ep))
        if "dedupe_nodes.nodes" in wanted:
            r = builder.dedupe_nodes(ep)
            if r:
                records.append(r)
    if "dedupe_edges.resolve_edge" in wanted:
        records.extend(builder.resolve_edge_negatives())
        if not args.no_synthetic_positives:
            records.extend(builder.resolve_edge_alias_positives())

    if args.report:
        _print_report(records)

    selected = apply_mix(records, rng, args.limit)
    weights = assign_loss_weights(selected, basis=args.loss_basis)
    if args.report:
        _print_mix(selected, weights)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "schemas.json").write_text(
        json.dumps({name: response_schema(name) for name in TARGET_MIX},
                   indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    if args.sample_only:
        path = args.out / "sample.jsonl"
        _write(path, selected[:args.limit or 20])
        logger.info("wrote %d sample records -> %s", min(len(selected), args.limit or 20),
                    path)
        return 0

    train, val = [], []
    for r in selected:
        (val if split_of(r["meta"]["article_id"] or "", args.val_fraction) == "val"
         else train).append(r)

    if args.upsample:
        upsampled = upsample_train(train, args.max_repeat, args.loss_basis)
        if args.report:
            _print_upsample_report(train, upsampled, val, args.max_repeat)
        train = upsampled

    _write(args.out / "train.jsonl", train)
    _write(args.out / "val.jsonl", val)
    logger.info("wrote %d train / %d val -> %s", len(train), len(val), args.out)
    return 0


def _write(path: Path, records: list[dict]) -> None:
    with path.open("w", encoding="utf-8") as fh:
        for r in records:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


def _print_report(records: list[dict]) -> None:
    counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in records:
        counts[r["prompt_name"]][r["meta"]["provenance"]] += 1
    logger.info("\n--- derivable from the graph, before mixing ---")
    for name in TARGET_MIX:
        buckets = counts.get(name, {})
        total = sum(buckets.values())
        detail = ", ".join(f"{k}={v}" for k, v in sorted(buckets.items())) or "none"
        logger.info("  %-40s %5d  (%s)", name, total, detail)
    logger.info("\n--- NOT derivable for free (needs authorisation) ---")
    logger.info("  dedupe_edges.resolve_edge  true positives: the merged-away fact text")
    logger.info("      is discarded by graphiti; only synthetic alias positives exist here.")
    logger.info("  dedupe_nodes.nodes         positives at all: the extracted duplicate")
    logger.info("      name is discarded on merge. This split is negatives-only.")
    logger.info("  extract_nodes.extract_summaries_batch: per-call summary state; the")
    logger.info("      graph holds only the final summary.\n")


def _print_mix(records: list[dict], weights: dict[str, float]) -> None:
    n: dict[str, int] = defaultdict(int)
    full: dict[str, int] = defaultdict(int)
    comp: dict[str, int] = defaultdict(int)
    for r in records:
        k = r["prompt_name"]
        n[k] += 1
        full[k] += sum(len(m["content"]) for m in r["messages"]) // 4
        comp[k] += max(1, len(r["messages"][-1]["content"]) // 4)
    tn, tf, tc = sum(n.values()), sum(full.values()), sum(comp.values())
    logger.info("--- realised mix (%d examples, ~%d tokens) ---", tn, tf)
    logger.info("  %-40s %7s %9s %11s %8s", "prompt", "n%", "tokens%", "completion%",
                "weight")
    for name in TARGET_MIX:
        if not n.get(name):
            continue
        logger.info("  %-40s %6.1f%% %8.1f%% %10.1f%% %8.2f", name,
                    100 * n[name] / tn, 100 * full[name] / tf, 100 * comp[name] / tc,
                    weights.get(name, 0.0))
    logger.info("  'completion%' is the SFT gradient share BEFORE meta.loss_weight is")
    logger.info("  applied; 'weight' restores TARGET_MIX. The spread is wide because a")
    logger.info("  resolve_edge target is ~12 tokens and a summary target ~1,494 -- a")
    logger.info("  trainer that cannot weight per example should upsample instead.\n")


def _print_upsample_report(before: list[dict], after: list[dict], val: list[dict],
                           max_repeat: int) -> None:
    """Report how close TRAIN repetition got to TARGET_MIX, and that val is untouched."""
    n_before: dict[str, int] = defaultdict(int)
    n_after: dict[str, int] = defaultdict(int)
    full_after: dict[str, int] = defaultdict(int)
    for r in before:
        n_before[r["prompt_name"]] += 1
    for r in after:
        n_after[r["prompt_name"]] += 1
        full_after[r["prompt_name"]] += sum(len(m["content"]) for m in r["messages"]) // 4
    total_after, total_full_after = sum(n_after.values()), sum(full_after.values())
    seen_max_repeat = max((r["meta"]["repeat_index"] for r in after), default=-1) + 1
    logger.info("--- upsample (max-repeat=%d, realised max=%d): TRAIN only ---",
                max_repeat, seen_max_repeat)
    logger.info("  val split unchanged: %d records (never upsampled)", len(val))
    logger.info("  %-40s %8s %8s %9s %10s %9s", "prompt", "before", "after", "n%",
                "tokens%", "target%")
    for name in TARGET_MIX:
        if not n_after.get(name):
            continue
        logger.info("  %-40s %8d %8d %8.1f%% %9.1f%% %8.1f%%", name,
                    n_before.get(name, 0), n_after[name],
                    100 * n_after[name] / total_after,
                    100 * full_after[name] / total_full_after,
                    100 * TARGET_MIX[name])
    logger.info("  rounding + the repeat cap mean this approaches but does not exactly")
    logger.info("  hit TARGET_MIX -- compare 'tokens%' above to 'target%'.\n")


